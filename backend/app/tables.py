from sqlalchemy import (
    BigInteger,
    Column,
    Date,
    Integer,
    MetaData,
    Numeric,
    SmallInteger,
    String,
    Table,
)
from sqlalchemy.dialects.mysql import BIGINT, DATETIME, INTEGER, SMALLINT

metadata = MetaData()

fund_archive = Table(
    "fund_archive",
    metadata,
    Column("fund_code", String(32), primary_key=True),
    Column("fund_name", String(128), nullable=False),
    Column("fund_type", String(32)),
    Column("manager_name", String(128)),
    Column("custodian_name", String(128)),
    Column("establish_date", Date),
    Column("currency", String(3)),
    Column("fund_status", String(16)),
    Column("etl_source_file", String(512)),
    Column("etl_batch_id", String(64)),
    Column("created_at", DATETIME(fsp=3), nullable=False),
    Column("updated_at", DATETIME(fsp=3), nullable=False),
)

fund_redemption_rule = Table(
    "fund_redemption_rule",
    metadata,
    Column("rule_id", BigInteger().with_variant(BIGINT(unsigned=True), "mysql"), primary_key=True),
    Column("fund_code", String(32), nullable=False),
    Column("version_no", Integer().with_variant(INTEGER(unsigned=True), "mysql"), nullable=False),
    Column("purchase_status", String(16)),
    Column("redeem_status", String(16)),
    Column("min_purchase_amount", Numeric(18, 2)),
    Column("min_additional_purchase_amount", Numeric(18, 2)),
    Column("daily_purchase_limit", Numeric(18, 2)),
    Column("min_redeem_shares", Numeric(18, 4)),
    Column("min_holding_shares", Numeric(18, 4)),
    Column("purchase_fee_rate", Numeric(10, 6)),
    Column("redeem_fee_rate", Numeric(10, 6)),
    Column("purchase_confirm_days", SmallInteger().with_variant(SMALLINT(unsigned=True), "mysql")),
    Column("redeem_confirm_days", SmallInteger().with_variant(SMALLINT(unsigned=True), "mysql")),
    Column("redeem_arrival_days", SmallInteger().with_variant(SMALLINT(unsigned=True), "mysql")),
    Column("effective_date", Date),
    Column("remark", String(512)),
    Column("source_type", String(8), nullable=False),
    Column("etl_batch_id", String(64)),
    Column("is_deleted", SmallInteger, nullable=False),
    Column("created_by", String(64), nullable=False),
    Column("created_at", DATETIME(fsp=3), nullable=False),
    Column("deleted_by", String(64)),
    Column("deleted_at", DATETIME(fsp=3)),
)
